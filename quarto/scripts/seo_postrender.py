"""Add a meta description to each page of the HTML book (Quarto post-render).

Quarto writes no description unless a page's front matter has one, and the
section pages are generated by convert_lbs.py, so this fills them in after the
render instead: "The Little Book of Semaphores, SECTION: " plus the page's first
real paragraph, cut to about 155 characters at a word. The home page gets
BOOK_DESCRIPTION. Pages that already have a description are left alone.

Run by `quarto render` (project: post-render in _quarto.yml); can also be run by
hand from quarto/:  python3 scripts/seo_postrender.py
"""

import glob
import html
import os
import re

BOOK = 'The Little Book of Semaphores'
BOOK_DESCRIPTION = (
    'The Little Book of Semaphores: a free textbook on synchronization in concurrent '
    'programming, built around reusable patterns, with a hint before each solution.'
)
DESC_LEN = 155


def text_of(fragment):
    t = re.sub(r'<[^>]+>', ' ', fragment)
    t = html.unescape(t).replace('\xa0', ' ')
    t = re.sub(r'\s+', ' ', t).strip()
    return re.sub(r' ([,.;:!?)])', r'\1', t)


def shorten(s, n):
    if len(s) <= n:
        return s
    return s[:n].rsplit(' ', 1)[0].rstrip(',;:') + '…'


def describe(page, is_index):
    if is_index:
        return BOOK_DESCRIPTION
    main = re.search(r'<main.*?</main>', page, re.S)
    if not main:
        return None
    t = re.search(r'<span class="chapter-title">(.*?)</span>', main.group(0), re.S)
    title = text_of(t.group(1)) if t else None
    for p in re.findall(r'<p[ >].*?</p>', main.group(0), re.S):
        para = text_of(p)
        if len(para) >= 60:
            prefix = f'{BOOK}, {title}: ' if title else f'{BOOK}: '
            return shorten(prefix + para, DESC_LEN)
    return None


def main():
    out = os.environ.get('QUARTO_PROJECT_OUTPUT_DIR', '_book')
    n = 0
    for path in glob.glob(os.path.join(out, '**', '*.html'), recursive=True):
        rel = os.path.relpath(path, out)
        if rel.startswith(('site_libs', 'assets')):
            continue
        page = open(path, encoding='utf-8').read()
        if re.search(r'<meta[^>]+name="description"', page):
            continue
        desc = describe(page, rel == 'index.html')
        if not desc:
            continue
        tag = f'<meta name="description" content="{html.escape(desc, quote=True)}">\n'
        m = re.search(r'<title>', page)
        if m:
            page = page[:m.start()] + tag + page[m.start():]
            with open(path, 'w', encoding='utf-8') as f:
                f.write(page)
            n += 1
    print(f'seo_postrender: descriptions added to {n} pages')

    # The home page's canonical is the folder URL; list it the same way in the sitemap
    sitemap = os.path.join(out, 'sitemap.xml')
    if os.path.exists(sitemap):
        s = open(sitemap, encoding='utf-8').read()
        s2 = re.sub(r'(<loc>[^<]*/)index\.html(</loc>)', r'\1\2', s)
        if s2 != s:
            with open(sitemap, 'w', encoding='utf-8') as f:
                f.write(s2)


if __name__ == '__main__':
    main()
